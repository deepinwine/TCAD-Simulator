export function detectInitialLocale(
  stored: string | null,
  browserLanguages: readonly string[],
): Locale {
  if (stored === 'zh-CN' || stored === 'en') return stored;
  return browserLanguages.some(language => language.toLowerCase().startsWith('zh'))
    ? 'zh-CN'
    : 'en';
}
